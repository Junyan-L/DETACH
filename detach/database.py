from sqlalchemy import Column, String, Integer, Float, DateTime, LargeBinary, ForeignKey
from sqlalchemy.orm import declarative_base, relationship

Base = declarative_base()

class Trace(Base):
    __tablename__ = 'trace'
    id = Column(Integer, primary_key=True)
    cls = Column(Integer)  # cls=1 for coronal hole, cls=2 for filament
    start_time = Column(DateTime)
    end_time = Column(DateTime)
    instance_num = Column(Integer)
    cycle = Column(Integer)
    average_score = Column(Float)
    average_latitude = Column(Float)
    latitude_std = Column(Float)
    average_area_ratio = Column(Float)
    area_ratio_std = Column(Float)
    average_area_km2 = Column(Float)
    area_km2_std = Column(Float)
    average_aia_193_intensity = Column(Float)
    aia_193_intensity_std = Column(Float)
    hgs_latitude_speed = Column(Float)
    hgs_latitude_speed_r = Column(Float)
    hgs_latitude_speed_std = Column(Float)
    hgs_longitude_speed = Column(Float)
    hgs_longitude_speed_r = Column(Float)
    hgs_longitude_speed_std = Column(Float)
    boundary_hgs_y_min = Column(Float)
    boundary_hgs_y_max = Column(Float)
    boundary_hgs_y_min_err = Column(Float)
    boundary_hgs_y_max_err = Column(Float)
    instances = relationship("Instance", backref='trace')
    flux = Column(Float)
    flux_relative_err = Column(Float)
    flux_pos = Column(Float)
    flux_pos_relative_err = Column(Float)
    flux_neg = Column(Float)
    flux_neg_relative_err = Column(Float)
    area_positive = Column(Float)  # 单位km2
    area_negative = Column(Float)
    B_average = Column(Float)
    B_err = Column(Float)
    B_pos = Column(Float)
    B_pos_err = Column(Float)
    B_neg = Column(Float)
    B_neg_err = Column(Float)
    B_abs_average = Column(Float)
    B_abs_err = Column(Float)
    unipolarity_degree = Column(Float)
    uni_deg_err = Column(Float)
    comment = Column(String(64))


class Instance(Base):
    __tablename__ = 'instance'
    id = Column(Integer, primary_key=True)
    frame_id = Column(Integer)
    source = Column(String(64))
    cls = Column(Integer)  # cls=1 for coronal hole, cls=2 for filament
    score = Column(Float)
    trace_id = Column(Integer, ForeignKey('trace.id'))
    time = Column(DateTime)
    box_x_min = Column(Float)
    box_y_min = Column(Float)
    box_x_max = Column(Float)
    box_y_max = Column(Float)
    box_Tx_min = Column(Float)
    box_Tx_max = Column(Float)
    box_Ty_min = Column(Float)
    box_Ty_max = Column(Float)
    mask = Column(LargeBinary)
    mask_hgs = Column(LargeBinary)
    mask_hgc = Column(LargeBinary)
    area_ratio = Column(Float)
    area_km2 = Column(Float)
    average_aia_193_intensity = Column(Float)
    center_hgs_lon = Column(Float)
    center_hgs_lat = Column(Float)
    center_hgc_lon = Column(Float)
    center_hgc_lat = Column(Float)
    boundary_hgs_lon_min = Column(Float)
    boundary_hgs_lon_max = Column(Float)
    boundary_hgs_lat_min = Column(Float)
    boundary_hgs_lat_max = Column(Float)
    flux = Column(Float)
    flux_positive = Column(Float)
    flux_negative = Column(Float)
    flux_percent_unbalanced = Column(Float)
    area_positive = Column(Float)
    area_negative = Column(Float)
    B_average = Column(Float)
    B_pos_avg = Column(Float)
    B_neg_avg = Column(Float)
    B_abs_average = Column(Float)
    unipolarity_degree = Column(Float)
    possible_trace_id = Column(String(64))
    comment = Column(String(64))
